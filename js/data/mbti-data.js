/**
 * 出題順序：五軸輪流出（E/I → S/N → T/F → J/P → A/T → E/I ⋯），
 * 避免同一軸連答 8 題時「慣性」作答。值為 QUESTIONS 的索引。
 */
export const ORDER = (() => {
  const byAxis = {};
  QUESTIONS.forEach((q, i) => { (byAxis[q.ax] = byAxis[q.ax] || []).push(i); });
  const keys = Object.keys(byAxis);
  const max = Math.max(...keys.map(k => byAxis[k].length));
  const out = [];
  for (let r = 0; r < max; r++) keys.forEach(k => { if (byAxis[k][r] !== undefined) out.push(byAxis[k][r]); });
  return out;
})();

