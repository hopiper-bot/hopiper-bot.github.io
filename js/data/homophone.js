/**
 * homophone.js — 諧音檢查資料
 *
 * 姓名學傳統講「音、形、義」。「音」除了聲調順不順（已做），
 * 還有一塊很實際的：整個名字連起來唸，會不會變成不雅或好笑的諧音。
 * 這是小孩實際會被同學亂叫的痛點，比命理吉凶更貼近生活。
 *
 * 為什麼用黑名單、不做全字典拼音比對？
 *   - 全字典拼音表要 2 萬字、體積大，而諧音問題其實高度集中在
 *     少數「經典陷阱組合」，做窮舉拼音反而會誤報一堆無傷大雅的巧合。
 *   - 諧音好不好笑很主觀，硬用演算法判斷會誤傷（例如很多正常名字
 *     拼音接近某個詞，但根本沒人會那樣聯想）。
 *   - 收錄「大家真的會拿來開玩笑」的組合，命中率高、誤報低。
 *
 * 三種檢查：
 *   1. FULL_NAME — 整個姓名（姓+名）完全等於某個經典諧音梗
 *   2. SURNAME_TRAP — 特定姓氏 + 名開頭字，容易連成不雅詞
 *   3. BAD_CHAR — 名字裡單獨帶了諧音不雅的字（不分姓氏）
 *
 * 語氣：點出來但不誇張，畢竟很多是無傷大雅的巧合，讓使用者自己判斷。
 */

